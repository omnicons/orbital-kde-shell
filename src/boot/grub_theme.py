#!/usr/bin/env python3
"""Generates Orbiter's GRUB theme, the GRUB counterpart of the Limine menu,
from tokens.toml: the same HUD wallpaper, framing GRUB's menu box.

  grub_theme.py [--size WxH] [--host NAME]

Writes build/boot/grub/orbiter/: theme.txt, background.png and the images
for the highlighted entry, plus fonts.list. GRUB needs its own font format
(.pf2), made with grub-mkfont, which only GRUB machines have; install-boot.sh
makes them from fonts.list ("<file name> <role> <pixel size>" per line).

Untested on a real GRUB boot so far.
"""
import argparse
import socket
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SRC))
import tokens as design_tokens  # noqa: E402  (src/tokens.py)

ROOT = SRC.parent

from PIL import Image  # noqa: E402

from limine_wallpaper import draw_wallpaper  # noqa: E402

OUT = ROOT / "build" / "boot" / "grub" / "orbiter"

# The framed area, as fractions of the screen, and what sits inside it.
FRAME = (0.22, 0.28, 0.78, 0.72)
BRANDING_TOP = 0.30
MENU = (0.24, 0.355, 0.52, 0.28)        # left, top, width, height
TIMEOUT_TOP = 0.655


def rgb(hex_colour):
    h = hex_colour.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def pct(fraction):
    # Whole numbers only: GRUB's parser stops at a decimal point and refuses
    # the whole theme ("unrecognized number").
    return f"{round(fraction * 100)}%"


def selection_images(v, height):
    """The highlighted entry as a 9-slice box: a bright fill with an accent
    edge on the left, the same as the launcher's current row."""
    edge = max(4, round(height / 400))
    fill, accent = rgb(v["text"]), rgb(v["accent"])
    return {
        "select_c.png": Image.new("RGBA", (8, 8), fill),
        "select_n.png": Image.new("RGBA", (8, 1), fill),
        "select_s.png": Image.new("RGBA", (8, 1), fill),
        "select_e.png": Image.new("RGBA", (1, 8), fill),
        "select_ne.png": Image.new("RGBA", (1, 1), fill),
        "select_se.png": Image.new("RGBA", (1, 1), fill),
        "select_w.png": Image.new("RGBA", (edge, 8), accent),
        "select_nw.png": Image.new("RGBA", (edge, 1), accent),
        "select_sw.png": Image.new("RGBA", (edge, 1), accent),
    }


def theme_txt(v, brand, height):
    s = height / 2400
    item_px = round(38 * s)
    label_px = round(34 * s)
    small_px = round(28 * s)
    mono = lambda px: f"Orbiter Mono Regular {px}"
    display = lambda px: f"Orbiter Display Regular {px}"
    left, top, width, menu_height = MENU
    return f"""# Generated by src/boot/grub_theme.py from tokens.toml; edit those instead.
title-text: ""
desktop-image: "background.png"
desktop-image-scale-method: "stretch"
desktop-color: "{v['bar']}"
terminal-font: "{mono(small_px)}"

+ label {{
    left = {pct(FRAME[0])}
    width = {pct(FRAME[2] - FRAME[0])}
    top = {pct(BRANDING_TOP)}
    height = {round(50 * s)}
    align = "center"
    text = "{brand.upper()} // BOOT SELECT"
    font = "{display(label_px)}"
    color = "{v['accent']}"
}}

+ boot_menu {{
    left = {pct(left)}
    top = {pct(top)}
    width = {pct(width)}
    height = {pct(menu_height)}
    item_font = "{mono(item_px)}"
    selected_item_font = "{mono(item_px)}"
    item_color = "{v['text']}"
    selected_item_color = "{v['bar']}"
    selected_item_pixmap_style = "select_*.png"
    item_height = {round(64 * s)}
    item_padding = {round(24 * s)}
    item_spacing = {round(6 * s)}
    icon_width = 0
    icon_height = 0
    item_icon_space = 0
    scrollbar = false
}}

# The auto-boot countdown: a thin accent bar and the seconds left.
+ progress_bar {{
    id = "__timeout__"
    left = {pct(left)}
    width = {pct(width)}
    top = {pct(TIMEOUT_TOP)}
    height = {round(10 * s)}
    show_text = false
    fg_color = "{v['accent']}"
    bg_color = "{v['ansi'][0]}"
    border_color = "{v['ansi'][0]}"
}}
+ label {{
    id = "__timeout__"
    left = {pct(left)}
    width = {pct(width)}
    top = {pct(TIMEOUT_TOP + 0.012)}
    height = {round(40 * s)}
    text = "AUTO-BOOT IN %d S"
    font = "{display(small_px)}"
    color = "{v['muted']}"
}}
""", [("orbiter-mono", "mono", item_px), ("orbiter-mono", "mono", small_px),
      ("orbiter-display", "display", label_px), ("orbiter-display", "display", small_px)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", default="3840x2400")
    parser.add_argument("--host", default=socket.gethostname())
    parser.add_argument("--variant", default="black")
    args = parser.parse_args()
    width, height = (int(n) for n in args.size.split("x"))
    tokens = design_tokens.load()
    v = tokens["variants"][args.variant]
    brand = tokens["brand"]["name"]

    OUT.mkdir(parents=True, exist_ok=True)
    box = tuple(round(f * d) for f, d in zip(FRAME, (width, height, width, height)))
    draw_wallpaper(width, height, v, args.host, brand, box).save(OUT / "background.png", optimize=True)
    for name, image in selection_images(v, height).items():
        image.save(OUT / name)
    text, fonts = theme_txt(v, brand, height)
    (OUT / "theme.txt").write_text(text)
    (OUT.parent / "fonts.list").write_text(
        "".join(f"{name}-{px}.pf2 {role} {px}\n" for name, role, px in dict.fromkeys(fonts)))


if __name__ == "__main__":
    main()
